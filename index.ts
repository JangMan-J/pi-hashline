type HashlineMode = OverrideMode;

const DEFAULT_SHORTCUT = "alt+h";

function resolveShortcuts(): string[] {
	try {
		const raw = JSON.parse(fs.readFileSync(path.join(getAgentDir(), "settings.json"), "utf8"));
		const cfg = raw?.["pi-hashline"]?.shortcut;
		if (cfg === false) return [];
		if (typeof cfg === "string") return cfg ? [cfg] : [];
		if (Array.isArray(cfg)) return cfg.filter((s): s is string => typeof s === "string" && s.length > 0);
	} catch {}
	return [DEFAULT_SHORTCUT];
}

interface OmpNatives {
	EditStore: new () => {
		recordSnapshot(absolutePath: string, text: string, seenLines?: number[] | null): string;
		recordSnapshotFile(absolutePath: string, seenLines?: number[] | null): string | null;
		recordSeenLines(absolutePath: string, tag: string, lines: number[]): void;
		recordSeenLinesFromBody(absolutePath: string, tag: string, body: string): void;
		invalidate(absolutePath: string): void;
		clear(): void;
	};
	EditSession: new (
		store: any,
		policy: {
			cwd: string;
			mode: string;
			allowFuzzy: boolean;
			fuzzyThreshold: number;
			enforceSeenLines: boolean;
			maxColumns: number;
			blockAutoGenerated: boolean;
			planActive: boolean;
			urlSchemes: string[];
			urlAliasSchemes: string[];
			planWritableRoots: string[];
			homeDir: string;
			rawInput: boolean;
		},
	) => {
		setArgsJson(argsJson: string): void;
		finish(): void;
		apply(
			req: { lspBatchId?: string; lspFlush: boolean },
			writer: (
				err: Error | null,
				req: { path: string; displayPath: string; op: string; moveTo?: string; content?: string },
			) => Promise<{ written: string; diagnosticsJson?: string }>,
		): Promise<{
			text: string;
			isError: boolean;
			errorKind?: string;
			files: Array<{
				path: string;
				displayPath: string;
				op: string;
				moveTo?: string;
				diff: string;
				firstChangedLine?: number;
				warnings: string[];
				parseRegressed: boolean;
			}>;
		}>;
		close(): void;
	};
	editDescription(mode: string): string;
	editInspect(mode: string, argsJson: string): { paths: string[]; fileOps: Array<{ kind: string; path: string; to?: string }> };
	hashlineFormatHeader(displayPath: string, tag: string): string;
	hashlineFormatNumberedLines(text: string, startLine?: number): string;
}

let cachedNatives: OmpNatives | undefined;

export function loadOmpNatives(): OmpNatives {
	if (cachedNatives) return cachedNatives;
	const req = createRequire(import.meta.url);
	const plat = process.platform;
	const arch = process.arch;
	const pkg = `@oh-my-pi/pi-natives-${plat}-${arch}`;
	const candidates =
		arch === "x64"
			? [`${pkg}/pi_natives.${plat}-${arch}-modern.node`, `${pkg}/pi_natives.${plat}-${arch}-baseline.node`]
			: [`${pkg}/pi_natives.${plat}-${arch}.node`];
	let lastErr: unknown;
	for (const id of candidates) {
		try {
			cachedNatives = req(id) as OmpNatives;
			return cachedNatives;
		} catch (err) {
			lastErr = err;
		}
	}
	throw new Error(`pi-hashline: failed to load native bindings (${candidates.join(", ")}): ${String(lastErr)}`);
}

function parseMode(raw: string | undefined): HashlineMode {
	const v = (raw ?? "").trim().toLowerCase();
	if (v === "0" || v === "off" || v === "false" || v === "replace") return "off";
	if (v === "force") return "force";
	if (v === "1" || v === "on" || v === "true" || v === "all") return "all";
	return "auto";
}

export function shouldUseHashline(
	mode: HashlineMode,
	model: { provider?: string; id?: string } | undefined,
	agentDir?: string,
): boolean {
	const cfg = loadConfigSync(agentDir);
	return resolveModelDecision(cfg, mode, model).use === "hashline";
}

function normalizeToLF(s: string): string {
	return s.replace(/\r\n/g, "\n").replace(/\r/g, "\n");
}

function formatDisplayPath(absPath: string, cwd: string): string {
	const rel = path.relative(cwd, absPath);
	if (rel && !rel.startsWith("..") && !path.isAbsolute(rel)) {
		return rel.split(path.sep).join("/");
	}
	const home = os.homedir();
	if (absPath === home) return "~";
	if (absPath.startsWith(home + path.sep)) return "~/" + absPath.slice(home.length + 1).split(path.sep).join("/");
	return absPath;
}

const READ_FOOTER_RE = /\n\n(\[(?:Showing lines [^\]]+|\d+ more lines in file\.[^\]]*)\])$/;

const hashlineSchema = Type.Object({
	input: Type.String({
		description:
			"One or more `[PATH#TAG]` sections with hashline operations (`PUT N.=M:`, `PUT N*:`, `PUT <N:`, `PUT >N:`, `PUT >$:`, `CUT`, `MV`, `REM`) and `+TEXT` body rows. Copy the 4-hex `#TAG` from the latest `read` or `hashline_edit` output.",
	}),
});

const COMPACT_DESCRIPTION = `Edit existing files with line-anchored hashline patches (no oldText echoed; use \`write\` for new files).

Each file section starts with \`[PATH#TAG]\`, copying the 4-hex \`TAG\` from the latest \`read\` or \`hashline_edit\` result. All line numbers refer to that tagged snapshot (never shifted by earlier hunks in the same call):

\`\`\`text
[src/example.ts#1A2B]
PUT 12.=15:
+const total = items.reduce((a, b) => a + b, 0);
+return total;
\`\`\`

Operations:
- \`PUT N.=M:\` — replace inclusive lines N..M with following \`+TEXT\` rows (\`PUT N.=N:\` for one line).
- \`PUT N*:\` — replace the multi-line syntax block (function/class/impl/section) starting on opener line N.
- \`PUT <N:\` / \`PUT >N:\` / \`PUT >$:\` — insert \`+TEXT\` rows before line N, after line N, or at EOF (\`PUT >N*:\` inserts after block N).
- \`CUT N.=M\` / \`CUT N*\` — delete lines or block (append \`@name\` to save into a register; paste later with \`PUT <N @name\`, \`PUT >N @name\`, or \`PUT N.=M @name\`, with no \`+\` body).
- \`MV dest/path\` — move/rename after prior section ops; \`REM\` — delete file.

Rules:
- Every body row on \`:\` ops starts with \`+\` followed by verbatim text including indentation; lone \`+\` writes a blank line. Literal leading \`-\` or \`+\` in content is escaped as \`+-...\` or \`++...\`.
- Never emit removed \`-\` lines or unchanged context lines. Split non-adjacent changes into separate \`PUT\`/\`CUT\` ops under the same \`[PATH#TAG]\` header.
- Only anchor lines visible in a prior \`read\`; after every edit the file's \`#TAG\` and line numbers update (use the returned header/preview or re-\`read\`).`;

function appendStatsRow(row: Record<string, unknown>): void {
	try {
		const file = path.join(getAgentDir(), "hashline-stats.jsonl");
		fs.mkdirSync(path.dirname(file), { recursive: true });
		fs.appendFileSync(file, JSON.stringify(row) + "\n", "utf8");
	} catch {}
}

export default function piHashlineExtension(pi: ExtensionAPI): void {
	let mode: HashlineMode = parseMode(process.env.PI_HASHLINE);
	let storeInstance: ReturnType<OmpNatives["EditStore"]> | undefined;
	let lastSessionFile: string | undefined;
	let activeThisRun = false;

	const getStore = () => {
		if (!storeInstance) {
			const natives = loadOmpNatives();
			storeInstance = new natives.EditStore();
		}
		return storeInstance;
	};

	pi.on("session_start", (_event, ctx) => {
		const sf = ctx.sessionManager.getSessionFile();
		if (sf !== lastSessionFile) {
			lastSessionFile = sf;
			storeInstance?.clear();
		}
	});

	pi.on("before_agent_start", (event, ctx) => {
		activeThisRun = shouldUseHashline(mode, ctx.model);
		const opts = event.systemPromptOptions;
		if (!opts?.selectedTools) return undefined;
		const hasEdit = opts.selectedTools.includes("edit");
		const hasHl = opts.selectedTools.includes("hashline_edit");
		if (activeThisRun) {
			if (hasEdit || !hasHl) {
				opts.selectedTools = opts.selectedTools.filter((t: string) => t !== "edit");
				if (!opts.selectedTools.includes("hashline_edit")) {
					const readIdx = opts.selectedTools.indexOf("read");
					if (readIdx >= 0) opts.selectedTools.splice(readIdx + 1, 0, "hashline_edit");
					else opts.selectedTools.push("hashline_edit");
				}
			}
		} else if (hasHl) {
			opts.selectedTools = opts.selectedTools.filter((t: string) => t !== "hashline_edit");
			if (!opts.selectedTools.includes("edit")) opts.selectedTools.push("edit");
		}
		return undefined;
	});

	// Format top-level text `read` results as `[path#TAG]\n1:line...` when hashline is active (and record snapshots always
	// so switching models mid-session already has tags warm). Leaves images and codemode nested calls (`parentToolCallId`) raw.
	pi.on("tool_result", async (event, ctx) => {
		if (event.isError) return undefined;
		const cwd = ctx?.cwd || process.cwd();

		if (event.toolName === "write") {
			const rawPath = (event.input as { path?: string } | undefined)?.path;
			if (!rawPath) return undefined;
			const abs = path.resolve(cwd, rawPath.replace(/^@/, ""));
			try {
				const natives = loadOmpNatives();
				const tag = getStore().recordSnapshotFile(abs);
				if (!tag || !activeThisRun || event.parentToolCallId) return undefined;
				const header = natives.hashlineFormatHeader(formatDisplayPath(abs, cwd), tag);
				const first = event.content?.[0];
				if (first?.type === "text") {
					const updated = `${first.text} (${header})`;
					return { content: [{ type: "text", text: updated }, ...(event.content?.slice(1) ?? [])] };
				}
			} catch {}
			return undefined;
		}

		if (event.toolName !== "read") return undefined;
		if (event.content?.some((c: any) => c?.type === "image")) return undefined;
		const first = event.content?.[0];
		if (!first || first.type !== "text") return undefined;
		if (first.text.startsWith("[Line ") || first.text.startsWith("Read image file [")) return undefined;

		const input = (event.input ?? {}) as { path?: string; offset?: number; limit?: number };
		if (!input.path) return undefined;
		const abs = path.resolve(cwd, input.path.replace(/^@/, ""));

		let tag: string | null = null;
		let natives: OmpNatives;
		try {
			natives = loadOmpNatives();
			tag = getStore().recordSnapshotFile(abs);
		} catch {
			return undefined;
		}
		if (!tag) return undefined;

		// Keep codemode (`tools.read`) raw so scripts doing JSON.parse(await tools.read(...)) never break.
		if (!activeThisRun || event.parentToolCallId) return undefined;

		const startLine = input.offset ? Math.max(1, Math.floor(input.offset)) : 1;
		let bodySource = first.text;
		let footer = "";
		const m = READ_FOOTER_RE.exec(bodySource);
		if (m) {
			footer = "\n\n" + m[1];
			bodySource = bodySource.slice(0, m.index);
		}

		const header = natives.hashlineFormatHeader(formatDisplayPath(abs, cwd), tag);
		const numbered = bodySource.length === 0 && startLine === 1 ? "" : natives.hashlineFormatNumberedLines(normalizeToLF(bodySource), startLine);
		getStore().recordSeenLinesFromBody(abs, tag, numbered);
		const finalText = numbered ? `${header}\n${numbered}${footer}` : `${header}${footer}`;
		return {
			content: [{ type: "text", text: finalText }, ...(event.content?.slice(1) ?? [])],
			structuredContent: finalText,
		};
	});

	pi.registerTool({
		name: "hashline_edit",
		label: "edit",
		description: COMPACT_DESCRIPTION,
		promptSnippet: "Edit existing files by `[PATH#TAG]` snapshot tag and line/block spans without echoing oldText",
		promptGuidelines: [
			"Read the target file range before editing to obtain its `[PATH#TAG]` header and `LINE:TEXT` numbers.",
			"Use `hashline_edit` for targeted changes to existing files (batch all ops for one or more files in a single call); use `write` only for new files or complete rewrites.",
			"Never include unchanged context lines or `-` lines in `hashline_edit` — emit `+TEXT` only for the replacement/inserted lines.",
		],
		parameters: hashlineSchema,

		async execute(_toolCallId, params, signal, _onUpdate, ctx: ExtensionContext) {
			const t0 = performance.now();
			const cwd = ctx?.cwd || process.cwd();
			const natives = loadOmpNatives();
			const store = getStore();
			const session = new natives.EditSession(store, {
				cwd,
				mode: "hashline",
				allowFuzzy: true,
				fuzzyThreshold: 0.95,
				enforceSeenLines: true,
				maxColumns: 2000,
				blockAutoGenerated: true,
				planActive: false,
				urlSchemes: [],
				urlAliasSchemes: [],
				planWritableRoots: [],
				homeDir: os.homedir(),
				rawInput: false,
			});

			let outcome: Awaited<ReturnType<typeof session.apply>>;
			try {
				session.setArgsJson(JSON.stringify({ input: params.input }));
				session.finish();
				outcome = await session.apply({ lspFlush: false }, async (_err, req) => {
					if (signal?.aborted) throw new Error("Operation aborted");
					return await withFileMutationQueue(req.path, async () => {
						if (signal?.aborted) throw new Error("Operation aborted");
						if (req.op === "delete") {
							await fsp.unlink(req.path);
							return { written: "" };
						}
						if (req.content === undefined) {
							throw new Error(`hashline_edit ${req.op} omitted content for ${req.displayPath}`);
						}
						if (req.op === "move") {
							if (!req.moveTo) throw new Error(`hashline_edit move omitted destination for ${req.displayPath}`);
							let srcMode: number | undefined;
							try {
								srcMode = (await fsp.stat(req.path)).mode & 0o7777;
							} catch {}
							await fsp.mkdir(path.dirname(req.moveTo), { recursive: true });
							await fsp.writeFile(req.moveTo, req.content, "utf8");
							if (srcMode !== undefined) {
								try {
									await fsp.chmod(req.moveTo, srcMode);
								} catch {}
							}
							await fsp.unlink(req.path);
							return { written: req.content };
						}
						if (req.op === "create") {
							await fsp.mkdir(path.dirname(req.path), { recursive: true });
						}
						await fsp.writeFile(req.path, req.content, "utf8");
						return { written: req.content };
					});
				});
			} finally {
				session.close();
			}

			const elapsedMs = Math.round((performance.now() - t0) * 100) / 100;
			appendStatsRow({
				ts: Date.now(),
				host: os.hostname(),
				model: ctx?.model ? `${ctx.model.provider}/${ctx.model.id}` : undefined,
				thinking: ctx?.thinkingLevel,
				inputBytes: Buffer.byteLength(params.input ?? "", "utf8"),
				ok: !outcome.isError,
				errorKind: outcome.errorKind,
				files: outcome.files.length,
				parseRegressed: outcome.files.some(f => f.parseRegressed),
				applyMs: elapsedMs,
			});

			if (outcome.isError) {
				return {
					content: [{ type: "text", text: outcome.text }],
					details: { diff: "", errorKind: outcome.errorKind },
					isError: true,
				};
			}

			const warnings: string[] = [];
			for (const f of outcome.files) {
				if (f.parseRegressed) {
					warnings.push(
						`Warning: ${f.displayPath} no longer parses cleanly after this edit. Re-read the edited region and fix any syntax error.`,
					);
				}
			}
			const combinedDiff = outcome.files
				.map(f => f.diff)
				.filter(Boolean)
				.join("\n");
			const firstChangedLine = outcome.files.find(f => f.firstChangedLine !== undefined)?.firstChangedLine;
			const textOut = warnings.length > 0 ? `${outcome.text}\n\n${warnings.join("\n")}` : outcome.text;

			return {
				content: [{ type: "text", text: textOut }],
				details: {
					diff: combinedDiff,
					firstChangedLine,
					files: outcome.files.map(f => ({
						path: f.moveTo ?? f.path,
						displayPath: f.displayPath,
						op: f.op,
						move: f.moveTo,
						parseRegressed: f.parseRegressed,
					})),
				},
			};
		},

		renderCall(args, theme) {
			let pathsLabel = "";
			try {
				const inspected = loadOmpNatives().editInspect("hashline", JSON.stringify(args ?? {}));
				if (inspected.paths.length > 0) pathsLabel = inspected.paths.join(", ");
			} catch {}
			if (!pathsLabel) {
				const m = /\[([^\]#\r\n]+)#/.exec(String(args?.input ?? ""));
				pathsLabel = m ? m[1] : "patch";
			}
			return new Text(theme.fg("toolTitle", theme.bold("hashline ")) + theme.fg("accent", pathsLabel), 0, 0);
		},

		renderResult(result, { expanded, isPartial }, theme) {
			if (isPartial) return new Text(theme.fg("warning", "Applying hashline patch..."), 0, 0);
			const firstText = result.content?.[0]?.type === "text" ? result.content[0].text : "";
			if ((result as any).isError) {
				const head = firstText.split("\n").slice(0, expanded ? 20 : 2).join("\n");
				return new Text(theme.fg("error", head || "hashline_edit failed"), 0, 0);
			}
			const diff = (result.details as { diff?: string } | undefined)?.diff ?? "";
			const diffLines = diff ? diff.split("\n") : [];
			let adds = 0;
			let dels = 0;
			for (const ln of diffLines) {
				if (ln.startsWith("+") && !ln.startsWith("+++")) adds++;
				else if (ln.startsWith("-") && !ln.startsWith("---")) dels++;
			}
			let out = theme.fg("success", `+${adds}`) + theme.fg("dim", " / ") + theme.fg("error", `-${dels}`);
			const summaryLine = firstText.split("\n")[0] ?? "";
			if (summaryLine) out += " " + theme.fg("muted", summaryLine);
			if (expanded && diffLines.length > 0) {
				const shown = diffLines.slice(0, 40);
				for (const ln of shown) {
					if (ln.startsWith("+")) out += `\n${theme.fg("success", ln)}`;
					else if (ln.startsWith("-")) out += `\n${theme.fg("error", ln)}`;
					else out += `\n${theme.fg("dim", ln)}`;
				}
				if (diffLines.length > 40) out += `\n${theme.fg("muted", `... ${diffLines.length - 40} more lines`)}`;
			}
			return new Text(out, 0, 0);
		},
	});

	const runningJobs = new Map<string, BenchJobState>();
	const lastBenchErrors = new Map<string, string>();
	const openMenu = async (ctx: ExtensionContext) => {
		await openHashlineMenu({
			ctx,
			getOverrideMode: () => mode,
			setOverrideMode: (next) => {
				mode = next;
			},
			runningJobs,
			lastBenchErrors,
		});
		activeThisRun = shouldUseHashline(mode, ctx.model);
	};

	pi.registerCommand("hashline", {
		description: "Open the Hashline edit routing & benchmark picker (Enter swap, Ctrl+B benchmark, Tab facets)",
		handler: async (_args, ctx) => {
			await openMenu(ctx);
		},
	});

	const seenShortcuts = new Set<string>();
	for (const shortcut of resolveShortcuts()) {
		const norm = shortcut.toLowerCase();
		if (seenShortcuts.has(norm)) continue;
		seenShortcuts.add(norm);
		pi.registerShortcut(shortcut as KeyId, {
			description: "Open Hashline edit routing & benchmark picker",
			handler: async (ctx) => {
				await openMenu(ctx);
			},
		});
	}
}
